export const getFamily = (id) => FAMILIES.find((f) => f.id === id);
export const getCompound = (id) => COMPOUNDS.find((c) => c.id === id);

// Groups compounds by family -> group, mirroring the compound tree.
export const buildTree = (compounds = COMPOUNDS) =>
  FAMILIES.map((family) => {
    const inFamily = compounds.filter((c) => c.family === family.id);
    const groups = [...new Set(inFamily.map((c) => c.group))].map((group) => ({
      name: group,
      compounds: inFamily.filter((c) => c.group === group),
    }));
    return { ...family, count: inFamily.length, groups };
  }).filter((f) => f.count > 0);
